package frontend.controllerSettings

fun keyboardLabel(id: Int): String = when (id) {
    8 -> "Backspace"
    9 -> "Tab"
    13 -> "Enter"
    16 -> "Shift"
    17 -> "Ctrl"
    18 -> "Alt"
    19 -> "Pause"
    20 -> "Caps Lock"
    27 -> "Esc"
    32 -> "Space"
    33 -> "Page Up"
    34 -> "Page Down"
    35 -> "End"
    36 -> "Home"
    37 -> "Left"
    38 -> "Up"
    39 -> "Right"
    40 -> "Down"
    45 -> "Insert"
    46 -> "Delete"
    in 48..57 -> (id - 48).toString()
    in 65..90 -> id.toChar().toString()
    91 -> "Meta"
    92 -> "Meta"
    93 -> "Menu"
    in 96..105 -> "Num ${id - 96}"
    106 -> "Num *"
    107 -> "Num +"
    109 -> "Num -"
    110 -> "Num ."
    111 -> "Num /"
    in 112..123 -> "F${id - 111}"
    144 -> "Num Lock"
    145 -> "Scroll Lock"
    173 -> "-"
    186 -> ";"
    187 -> "="
    188 -> ","
    189 -> "-"
    190 -> "."
    191 -> "/"
    192 -> "`"
    219 -> "["
    220 -> "\\"
    221 -> "]"
    222 -> "'"
    else -> "Key $id"
}
